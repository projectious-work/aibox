"""Install, regenerate, and check the projectious.work company standards.

The standards bundle is the `standards/` directory of
https://github.com/projectious-work/standards. A consumer repository vendors
it as `.standards/` (including this script) and gets two generated views:

- one skill per standard group in `.agents/skills/standard-*/SKILL.md`, with
  `.claude/skills/standard-*` symlinks to them;
- an always-on block in the repository's `AGENTS.md` between the
  COMPANY_STANDARDS markers.

Usage (from a checkout of the standards repository at a release tag):

    python3 scripts/standards.py install <consumer-repo> [--allow-unreleased]
    python3 scripts/standards.py sync [--check]            # this repo itself

Usage inside a consumer repository:

    python3 .standards/standards.py check   # exit 1 on drift or local edits
    python3 .standards/standards.py sync    # regenerate skills and AGENTS.md
    python3 .standards/standards.py check-specs [--base <ref>]   # spec layout

Never edit `.standards/` or the generated views by hand: change the standard
upstream, release it, and install the new version.
"""
