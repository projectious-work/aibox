GENERATED = "<!-- generated by standards.py from projectious-work/standards; do not edit -->"
LEGACY_BLOCK = re.compile(r"<!-- BEGIN ALWAYS_ON\b.*?<!-- END ALWAYS_ON -->\n?", re.S)


def fail(msg):
    sys.exit(f"error: {msg}")


def read(path):
    return path.read_text(encoding="utf-8")


def write(path, text):
    path.write_text(text, encoding="utf-8")


# ---------- generation ----------

def title(path, text):
    m = re.search(r"^# (.+)$", text, re.M)
    if not m:
        fail(f"{path} has no '# ' title")
    return m.group(1).strip()


def briefing(bundle, name):
    path = bundle / name
    if not path.is_file():
        fail(f"{path} not found")
    m = re.search(r"^## Agent briefing\n(.*?)(?=^## |\Z)", read(path), re.M | re.S)
    if not m:
        fail(f"{path} has no '## Agent briefing' section")
    return "\n".join(l[2:] if l.startswith("> ") else l.lstrip(">")
                     for l in m.group(1).strip().splitlines())


def sections(text):
    return [h for h in re.findall(r"^## (.+)$", text, re.M)
            if h != "Agent briefing"]


def skill_text(bundle, prefix, skill, desc, files):
    parts = [f"---\nname: {skill}\ndescription: {desc}\n---\n",
             f"# {skill}\n", GENERATED + "\n",
             "Binding company standard. The rules below are the summary; the "
             "linked file is authoritative. Read only the section the task "
             "needs.\n"]
    for f in files:
        path = bundle / f
        text = read(path)
        parts.append(f"## {title(path, text)}\n")
        parts.append(briefing(bundle, f).strip() + "\n")
        parts.append(f"Full standard: `{prefix}{f}`. Sections:\n")
        parts.append("\n".join(f"- {s}" for s in sections(text)) + "\n")
    return "\n".join(parts)


def block_text(bundle, prefix, version, consumer):
    if consumer:
        intro = (f"Company standards {version} from <{SOURCE_URL}>, vendored in "
                 f"`{prefix}` (license: `{prefix}README.md`). `standard-*` "
                 "skills load on demand; the full standard they name is "
                 f"authoritative. *Italic* terms are [Semantic Anchors]({ANCHORS}): "
                 "canonical meaning applies; standards state only deviations. "
                 f"Never edit `{prefix}`, the skills, or this block; run "
                 f"`python3 {prefix}standards.py check`.")
    else:
        intro = ("Generated from `standards/` by `scripts/standards.py sync`; "
                 "`standard-*` skills load on demand. *Italic* terms are "
                 f"[Semantic Anchors]({ANCHORS}): canonical meaning applies; "
                 "standards state only deviations.")
    lines = [BEGIN, "", intro, ""]
    for heading, f in ALWAYS_ON:
        lines += [f"### Always on: {heading}", "",
                  briefing(bundle, f).strip(), f"Details: `{prefix}{f}`.", ""]
    lines.append(END)
    return "\n".join(lines) + "\n"


def agents_text(agents_path, block):
    text = read(agents_path) if agents_path.exists() else "# AGENTS.md\n"
    text = LEGACY_BLOCK.sub("", text)
    nb, ne = text.count(BEGIN), text.count(END)
    if nb == 0 and ne == 0:
        return text.rstrip("\n") + "\n\n## Company standards\n\n" + block
    if nb != 1 or ne != 1:
        fail(f"{agents_path}: COMPANY_STANDARDS markers must appear once each")
    if text.index(END) < text.index(BEGIN):
        fail(f"{agents_path}: COMPANY_STANDARDS END marker comes before BEGIN")
    pre, rest = text.split(BEGIN)
    _, post = rest.split(END, 1)
    return pre + block.rstrip("\n") + post


def expected_outputs(target, bundle, prefix, version, consumer):
    out = {}
    for skill, desc, files in SKILLS:
        out[target / ".agents/skills" / skill / "SKILL.md"] = \
            skill_text(bundle, prefix, skill, desc, files)
    out[target / "AGENTS.md"] = agents_text(
        target / "AGENTS.md", block_text(bundle, prefix, version, consumer))
    return out


def link_dest(skill):
    return Path("../../.agents/skills") / skill


def is_generated_skill_dir(d):
    skill = d / "SKILL.md"
    return (d.is_dir() and not d.is_symlink() and skill.is_file()
            and [p.name for p in d.iterdir()] == ["SKILL.md"]
            and GENERATED in read(skill))


def is_generated_link(l):
    return l.is_symlink() and Path(os.readlink(l)) == link_dest(l.name)


# ---------- bundle and lock ----------

def bundle_files(bundle):
    return sorted(p for p in bundle.rglob("*")
                  if p.is_file() and p.name != LOCK and "__pycache__" not in p.parts)


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def lock_data(bundle, version, commit):
    return {"source": SOURCE_URL, "version": version, "commit": commit,
            "files": {p.relative_to(bundle).as_posix(): digest(p)
                      for p in bundle_files(bundle)}}


def git(repo, *args):
    try:
        r = subprocess.run(["git", "-C", str(repo), *args],
                           capture_output=True, text=True)
    except FileNotFoundError:
        fail("git is required but was not found")
    return r.stdout.strip() if r.returncode == 0 else None


# ---------- specifications ----------

SLUG = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
SPEC_REQUIRED = ["SPEC.toml", "requirements.md", "journeys.md", "overview.md"]
SPEC_META = {"SPEC.toml", "CHANGES.md", "FREEZE.sha256"}


def spec_files(vdir):
    return sorted(p.relative_to(vdir).as_posix() for p in vdir.rglob("*")
                  if p.is_file() and p.name != "FREEZE.sha256")


def freeze_lines(vdir):
    return "".join(f"{digest(vdir / f)}  {f}\n" for f in spec_files(vdir))


def parse_freeze(text):
    entries = {}
    for line in text.splitlines():
        m = re.match(r"([0-9a-f]{64}) [ *](.+)$", line)
        if m:
            entries[m.group(2)] = m.group(1)
        elif line.strip():
            entries[f"<malformed line: {line}>"] = ""
    return entries


def load_toml(text):
    try:
        import tomllib
    except ImportError:
        fail("check-specs needs Python 3.11 or later (tomllib)")
    return tomllib.loads(text)


def check_version(root, slug, n, vdir, errors, require_tag):
    where = f"spec/{slug}/v{n}"
    for f in SPEC_REQUIRED:
        if not (vdir / f).is_file():
            errors.append(f"{where}: missing {f}")
    catalogs = [p for p in vdir.glob("interfaces.*")
                if p.suffix in (".toml", ".yaml", ".yml", ".json")]
    if not catalogs:
        errors.append(f"{where}: missing interfaces.toml|yaml|yml|json")
    try:
        meta = load_toml(read(vdir / "SPEC.toml"))
    except (OSError, ValueError) as e:
        errors.append(f"{where}/SPEC.toml: {e}")
        return None
    if meta.get("slug") != slug or meta.get("version") != n:
        errors.append(f"{where}/SPEC.toml: slug/version must be {slug!r}/{n}")
    expected_sup = f"{slug}@v{n - 1}" if n > 1 else None
    if meta.get("supersedes") != expected_sup:
        errors.append(f"{where}/SPEC.toml: supersedes must be {expected_sup!r}")
    status = meta.get("status")
    freeze = vdir / "FREEZE.sha256"
    if status == "frozen":
        if not freeze.is_file():
            errors.append(f"{where}: frozen but FREEZE.sha256 is missing")
        elif parse_freeze(read(freeze)) != parse_freeze(freeze_lines(vdir)):
            errors.append(f"{where}: files do not match FREEZE.sha256")
        tag = f"spec/{slug}/v{n}"
        if not require_tag:
            pass
        elif git(root, "rev-parse", "-q", "--verify", f"refs/tags/{tag}") is None:
            errors.append(f"{where}: tag {tag} is missing")
        elif git(root, "diff", "--quiet", tag, "--", f"spec/{slug}/v{n}") is None:
            errors.append(f"{where}: content differs from tag {tag}")
    elif status == "draft":
        if freeze.exists():
            errors.append(f"{where}: draft must not contain FREEZE.sha256")
    else:
        errors.append(f"{where}/SPEC.toml: status must be draft or frozen")
    if n > 1:
        changes = vdir / "CHANGES.md"
        prev = vdir.parent / f"v{n - 1}"
        if not changes.is_file():
            errors.append(f"{where}: missing CHANGES.md")
        elif prev.is_dir():
            listed = set(re.findall(r"`([^`]+)`", read(changes)))
            a, b = set(spec_files(prev)), set(spec_files(vdir))
            differ = {f for f in a | b if f not in SPEC_META and
                      (f not in a or f not in b or
                       digest(prev / f) != digest(vdir / f))}
            for f in sorted(differ - listed):
                errors.append(f"{where}/CHANGES.md: does not list changed file {f}")
            for f in sorted((listed & (a | b)) - differ - SPEC_META):
                errors.append(f"{where}/CHANGES.md: lists unchanged file {f}")
    return status


def cmd_check_specs(root, base):
    spec_root = root / "spec"
    errors, frozen = [], set()
    frozen_at_base = set()
    if base:
        if git(root, "rev-parse", "-q", "--verify", f"{base}^{{commit}}") is None:
            fail(f"unknown --base ref {base}")
        listing = git(root, "ls-tree", "-r", "--name-only", base, "--", "spec") or ""
        for line in listing.splitlines():
            if line.endswith("/SPEC.toml"):
                try:
                    meta = load_toml(git(root, "show", f"{base}:{line}") or "")
                except ValueError:
                    continue
                if meta.get("status") == "frozen":
                    frozen_at_base.add(line[:-len("SPEC.toml")])
    if spec_root.is_dir():
        for sdir in sorted(p for p in spec_root.iterdir() if p.is_dir()):
            slug = sdir.name
            if not SLUG.match(slug) or re.search(r"-v\d+$", slug):
                errors.append(f"spec/{slug}: invalid slug")
                continue
            versions = sorted(int(p.name[1:]) for p in sdir.iterdir()
                              if p.is_dir() and re.fullmatch(r"v[1-9]\d*", p.name))
            others = [p.name for p in sdir.iterdir()
                      if not re.fullmatch(r"v[1-9]\d*", p.name)]
            if others:
                errors.append(f"spec/{slug}: unexpected entries {sorted(others)}")
            if versions != list(range(1, len(versions) + 1)):
                errors.append(f"spec/{slug}: versions must be v1..vN without gaps")
            for n in versions:
                d = f"spec/{slug}/v{n}/"
                if check_version(root, slug, n, sdir / f"v{n}", errors,
                                 not base or d in frozen_at_base) == "frozen":
                    frozen.add(f"spec/{slug}/v{n}/")
    if base:
        diff = git(root, "diff", "--name-status", "--no-renames", base, "--", "spec")
        if diff is None:
            fail(f"cannot diff against {base}")
        for line in diff.splitlines():
            kind, path = line.split("\t", 1)
            if kind != "A" and any(path.startswith(d) for d in frozen_at_base):
                errors.append(f"{path}: frozen at {base}; create the next version instead")
            elif kind == "D":
                errors.append(f"{path}: specification files are never deleted")
    for e in errors:
        print(f"error: {e}")
    print(f"specifications: {'ok' if not errors else f'{len(errors)} error(s)'}")
    sys.exit(1 if errors else 0)


# ---------- commands ----------

def apply(target, bundle, prefix, version, consumer, check):
    outputs = expected_outputs(target, bundle, prefix, version, consumer)
    known = {s for s, _, _ in SKILLS}
    problems, actions = [], []
    for p, text in outputs.items():
        if p.is_symlink() or (p.exists() and not p.is_file()):
            fail(f"{p} is not a regular file; remove it and rerun")
        if p.parent.name in known and p.parent.exists() and not p.parent.is_symlink() \
                and not p.exists() and any(p.parent.iterdir()):
            fail(f"{p.parent} exists but was not generated; rename it and rerun")
        if p.name == "SKILL.md" and p.is_file() and GENERATED not in read(p):
            fail(f"{p} was not generated by this script; rename its skill and rerun")
        if not p.is_file() or read(p) != text:
            problems.append(p)
            actions.append(("write", p, text))
    for skill in sorted(known):
        l = target / ".claude/skills" / skill
        if is_generated_link(l):
            continue
        if l.exists() or l.is_symlink():
            fail(f"{l} exists but is not the generated link to "
                 f"{link_dest(skill)}; remove or rename it and rerun")
        problems.append(l)
        actions.append(("link", l, link_dest(skill)))
    for d in sorted((target / ".agents/skills").glob("standard-*")):
        if d.name not in known and is_generated_skill_dir(d):
            problems.append(d)
            actions.append(("rmdir", d, None))
    for l in sorted((target / ".claude/skills").glob("standard-*")):
        if l.name not in known and is_generated_link(l):
            problems.append(l)
            actions.append(("unlink", l, None))
    if check:
        for p in problems:
            print(f"stale: {p.relative_to(target)}")
        return not problems
    for kind, p, arg in actions:
        p.parent.mkdir(parents=True, exist_ok=True)
        if kind == "write":
            write(p, arg)
        elif kind == "link":
            p.symlink_to(arg)
        elif kind == "rmdir":
            shutil.rmtree(p)
        else:
            p.unlink()
        print(f"{kind}: {p.relative_to(target)}")
    return True


def cmd_install(source_root, target, allow_unreleased):
    if not target.is_dir():
        fail(f"target {target} is not a directory")
    if target == source_root:
        fail("install into a consumer repository, not into the standards "
             "repository itself (use 'sync' here)")
    if git(source_root, "status", "--porcelain") != "":
        fail("the standards checkout is not a clean git checkout")
    commit = git(source_root, "rev-parse", "HEAD")
    version = git(source_root, "describe", "--tags", "--exact-match")
    if not version:
        if not allow_unreleased:
            fail("HEAD is not a release tag; check out a tag or pass "
                 "--allow-unreleased")
        version = f"unreleased-{commit[:12]}"
    dest = target / VENDOR_DIR
    if dest.is_symlink():
        fail(f"{dest} is a symlink; remove it and rerun")
    if dest.exists():
        lock = dest / LOCK
        try:
            ours = json.loads(read(lock)).get("source") == SOURCE_URL
        except (OSError, ValueError):
            ours = False
        if not ours:
            fail(f"{dest} exists and was not installed by this script; "
                 "move it away and rerun")
        shutil.rmtree(dest)
    shutil.copytree(source_root / "standards", dest,
                    ignore=shutil.ignore_patterns("__pycache__"))
    shutil.copy2(Path(__file__), dest / "standards.py")
    shutil.copy2(source_root / "LICENSE-CODE", dest / "LICENSE-CODE")
    write(dest / LOCK, json.dumps(lock_data(dest, version, commit), indent=2) + "\n")
    apply(target, dest, f"{VENDOR_DIR}/", version, True, check=False)
    print(f"installed company standards {version} ({commit[:12]}) "
          f"into {target / VENDOR_DIR}")


def consumer_context():
    bundle = Path(__file__).resolve().parent
    lock_path = bundle / LOCK
    if not lock_path.is_file():
        fail(f"{lock_path} not found; install the standards first")
    return bundle.parent, bundle, json.loads(read(lock_path))


def verify_lock(bundle, lock):
    ok = True
    actual = lock_data(bundle, lock["version"], lock["commit"])["files"]
    for name in sorted(set(lock["files"]) | set(actual)):
        if lock["files"].get(name) != actual.get(name):
            print(f"modified: {VENDOR_DIR}/{name}")
            ok = False
    return ok


def parse_base(rest):
    if not rest:
        return None
    if len(rest) == 2 and rest[0] == "--base":
        return rest[1]
    fail("usage: standards.py check-specs [--base <ref>]")


def main(argv):
    script_dir = Path(__file__).resolve().parent
    cmd, rest = (argv[0], argv[1:]) if argv else ("", [])
    if (script_dir / LOCK).is_file():
        target, bundle, lock = consumer_context()
        if cmd == "check" and not rest:
            ok = verify_lock(bundle, lock)
            ok = apply(target, bundle, f"{VENDOR_DIR}/", lock["version"], True,
                       check=True) and ok
            print(f"company standards {lock['version']}: {'ok' if ok else 'DRIFT'}")
            sys.exit(0 if ok else 1)
        if cmd == "sync" and not rest:
            if not verify_lock(bundle, lock):
                fail(f"{VENDOR_DIR}/ was edited; reinstall a release instead")
            apply(target, bundle, f"{VENDOR_DIR}/", lock["version"], True, check=False)
            return
        if cmd == "check-specs":
            return cmd_check_specs(target, parse_base(rest))
        fail("usage: standards.py check | sync | check-specs [--base <ref>]")
    root = script_dir.parent
    if cmd == "install" and rest and set(rest[1:]) <= {"--allow-unreleased"}:
        return cmd_install(root, Path(rest[0]).resolve(),
                           "--allow-unreleased" in rest)
    if cmd == "check-specs":
        return cmd_check_specs(root, parse_base(rest))
    if cmd == "sync" and rest in ([], ["--check"]):
        ok = apply(root, root / "standards", "standards/", "", False,
                   check=rest == ["--check"])
        sys.exit(0 if ok else 1)
    fail("usage: standards.py install <consumer-repo> [--allow-unreleased] "
         "| sync [--check] | check-specs [--base <ref>]")


if __name__ == "__main__":
    main(sys.argv[1:])
