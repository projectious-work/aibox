fn write_if_changed(path: &Path, content: &str) -> Result<bool> {
    crate::context::write_if_changed(path, content)
}

// Header is intentionally version-free so a clean container rebuild on a new
// CLI version doesn't dirty `git status` for files whose semantic content
// hasn't changed. The CLI version that performed the install is recorded in
// aibox.lock (the canonical place); stamping it into every generated file's
// header just produced rebuild churn. See v0.18.7 devcontainer drift fix.
const HEADER_TEMPLATE: &str = "# Generated by aibox — do not edit manually.\n# To modify, edit aibox.toml and run: aibox apply\n";
const IMAGE_TAG_RUNTIME_CUTOFF_MINOR: u64 = 27;

fn dockerfile_image_tag(base: &BaseImage, version: &str) -> String {
    match version {
        "latest" if current_cli_uses_runtime_image_tag() => {
            format!("base-{}-runtime-latest", base)
        }
        "latest" => format!("base-{}-latest", base),
        _ if should_use_runtime_image_tag(version) => format!("base-{}-runtime-v{}", base, version),
        _ => format!("base-{}-v{}", base, version),
    }
}

fn current_cli_uses_runtime_image_tag() -> bool {
    should_use_runtime_image_tag(env!("CARGO_PKG_VERSION"))
}

fn should_use_runtime_image_tag(version: &str) -> bool {
    let Ok(parsed) = semver::Version::parse(version) else {
        return false;
    };

    parsed.major > 0 || parsed.minor >= IMAGE_TAG_RUNTIME_CUTOFF_MINOR
}

/// Create a minijinja environment with embedded templates.
fn create_template_env() -> minijinja::Environment<'static> {
    let mut env = minijinja::Environment::new();
    env.set_trim_blocks(true);
    env.set_lstrip_blocks(true);
    env.add_template("Dockerfile", include_str!("templates/Dockerfile.j2"))
        .expect("Failed to add Dockerfile template");
    env.add_template(
        "docker-compose.yml",
        include_str!("templates/docker-compose.yml.j2"),
    )
    .expect("Failed to add docker-compose template");
    env
}

pub(crate) fn sanitize_compose_project_name(name: &str) -> String {
    let mut sanitized = String::new();
    let mut last_was_separator = false;

    for ch in name.chars().map(|ch| ch.to_ascii_lowercase()) {
        if ch.is_ascii_alphanumeric() {
            sanitized.push(ch);
            last_was_separator = false;
        } else if !last_was_separator && !sanitized.is_empty() {
            sanitized.push('-');
            last_was_separator = true;
        }
    }

    while sanitized.ends_with('-') {
        sanitized.pop();
    }

    if sanitized.is_empty() {
        "aibox".to_string()
    } else {
        sanitized
    }
}

fn project_path(path: &str) -> PathBuf {
    PathBuf::from(path)
}

fn parent_dir(path: &Path) -> &Path {
    path.parent()
        .filter(|parent| !parent.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."))
}

fn normalized_relative_components(path: &Path) -> Vec<String> {
    path.components()
        .filter_map(|component| match component {
            Component::Normal(value) => Some(value.to_string_lossy().into_owned()),
            Component::CurDir => None,
            _ => Some(component.as_os_str().to_string_lossy().into_owned()),
        })
        .collect()
}

fn relative_path(from_dir: &Path, target: &Path) -> String {
    if target.is_absolute() {
        return target.to_string_lossy().into_owned();
    }
    let from = normalized_relative_components(from_dir);
    let to = normalized_relative_components(target);
    let common = from
        .iter()
        .zip(to.iter())
        .take_while(|(a, b)| a == b)
        .count();
    let mut result = Vec::new();
    for _ in common..from.len() {
        result.push("..".to_string());
    }
    result.extend(to.into_iter().skip(common));
    if result.is_empty() {
        ".".to_string()
    } else {
        result.join("/")
    }
}

/// Generate all devcontainer files from the config.
pub fn generate_all(config: &AiboxConfig) -> Result<()> {
    let dockerfile_path = project_path(&config.container.paths.dockerfile);
    let docker_compose_path = project_path(&config.container.paths.docker_compose);
    let devcontainer_json_path = project_path(&config.container.paths.devcontainer_json);
    for path in [
        &dockerfile_path,
        &docker_compose_path,
        &devcontainer_json_path,
    ] {
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)
                .with_context(|| format!("Failed to create {}", parent.display()))?;
        }
    }

    output::info("Generating devcontainer files...");

    let mut effective_config = config.clone();
    if effective_config.container.image.version == "latest" {
        let flavor = effective_config.container.image.base.to_string();
        match crate::update::fetch_latest_image_version(&flavor) {
            Ok(v) => {
                effective_config.container.image.version = image_version_for_generation(v);
                effective_config.image.version = effective_config.container.image.version.clone();
            }
            Err(e) => {
                crate::output::warn(&format!(
                    "[container.image].release_version = \"latest\" but image version resolution failed during generation: {}. \
                     Generated files may reference an invalid tag. Consider re-running with network access or pinning an explicit version.",
                    e
                ));
            }
        }
    }

    // Create template environment once and reuse for all template-based files
    let env = create_template_env();

    if generate_dockerfile(&effective_config, &dockerfile_path, &env)? {
        output::ok(&format!("Generated {}", dockerfile_path.display()));
    }

    if generate_docker_compose(&effective_config, &docker_compose_path, &env)? {
        output::ok(&format!("Generated {}", docker_compose_path.display()));
    }

    if generate_devcontainer_json(&effective_config, &devcontainer_json_path)? {
        output::ok(&format!("Generated {}", devcontainer_json_path.display()));
    }

    Ok(())
}

pub(crate) fn image_version_for_generation(published_latest: Version) -> String {
    format!(
        "{}.{}.{}",
        published_latest.major, published_latest.minor, published_latest.patch
    )
}

/// Generate the Dockerfile. Returns true if file was written.
fn generate_dockerfile(
    config: &AiboxConfig,
    path_or_dir: &Path,
    env: &minijinja::Environment<'static>,
) -> Result<bool> {
    let header = HEADER_TEMPLATE.to_string();
    let dockerfile_path = if path_or_dir.is_dir() {
        path_or_dir.join("Dockerfile")
    } else {
        path_or_dir.to_path_buf()
    };
    let dockerfile_local_path = if path_or_dir.is_dir() {
        path_or_dir.join("Dockerfile.local")
    } else {
        project_path(&config.container.paths.dockerfile_local)
    };

    // Read Dockerfile.local if it exists
    let local_content = {
        match fs::read_to_string(&dockerfile_local_path) {
            Ok(raw) => {
                let trimmed = raw.trim_end_matches('\n');
                if trimmed.trim().is_empty() {
                    None
                } else {
                    Some(trimmed.to_string())
                }
            }
            Err(_) => None,
        }
    };

    let tmpl = env
        .get_template("Dockerfile")
        .context("Failed to load Dockerfile template")?;

    // Build addon Dockerfile content (builder stages + runtime commands).
    // AI providers are resolved into addons at config load time, so they
    // flow through this pipeline automatically — no hardcoded template logic.
    let addon_output = crate::addons::generate_dockerfile_content(&config.addons)?;
    let addon_builder_stages = addon_output.builder_stages;
    let addon_commands = addon_output.runtime_commands;

    let content = tmpl
        .render(context! {
            header => header,
            registry => crate::config::IMAGE_REGISTRY,
            image_tag => dockerfile_image_tag(&config.container.image.base, &config.container.image.version),
            version => config.container.image.version,
            profile => config.aibox.profile.to_string(),
            addon_builder_stages => addon_builder_stages,
            addon_commands => addon_commands,
            local_content => local_content,
        })
        .context("Failed to render Dockerfile template")?;

    write_if_changed(&dockerfile_path, &content)
}

/// Generate docker-compose.yml. Returns true if file was written.
fn generate_docker_compose(
    config: &AiboxConfig,
    path_or_dir: &Path,
    env: &minijinja::Environment<'static>,
) -> Result<bool> {
    let header = HEADER_TEMPLATE.to_string();
    let workspace_dir = config.workspace_dir();
    let legacy_dir_arg = path_or_dir.is_dir();
    let compose_path = if path_or_dir.is_dir() {
        path_or_dir.join("docker-compose.yml")
    } else {
        path_or_dir.to_path_buf()
    };
    let compose_dir = parent_dir(&compose_path);

    // Compose paths must be relative to the compose file's directory.
    let host_root = config.host_root_dir();
    let host_root_str = if legacy_dir_arg && host_root.is_relative() {
        format!("../{}", host_root.to_string_lossy())
    } else if host_root.is_relative() {
        relative_path(compose_dir, &host_root)
    } else {
        host_root.to_string_lossy().into_owned()
    };

    // Build environment map (BTreeMap for sorted keys)
    let mut env_vars: BTreeMap<String, String> = BTreeMap::new();
    env_vars.insert("TZ".to_string(), "Europe/Berlin".to_string());
    env_vars.insert("LANG".to_string(), "en_US.UTF-8".to_string());
    env_vars.insert("COLORTERM".to_string(), "truecolor".to_string());
    env_vars.insert("TERM".to_string(), "xterm-256color".to_string());
    env_vars.insert("SHELL".to_string(), "/bin/bash".to_string());
    let audio = if config.container.audio.enabled {
        &config.container.audio
    } else {
        &config.audio
    };
    if audio.enabled {
        env_vars.insert("PULSE_SERVER".to_string(), audio.pulse_server.clone());
        env_vars.insert("AUDIODRIVER".to_string(), "pulseaudio".to_string());
    }

    let compose_override_path = if legacy_dir_arg {
        path_or_dir.join("docker-compose.override.yml")
    } else {
        project_path(&config.container.paths.docker_compose_override)
    };
    let codex_sandbox_seccomp = config.ai.harnesses.contains(&AiHarness::Codex)
        && !compose_override_declares_codex_seccomp(&compose_override_path, &config.container.name);

    // S5 — BR-SEC-HARDEN: require explicit consent before emitting seccomp=unconfined.
    if codex_sandbox_seccomp && !config.security.acknowledge_seccomp_unconfined {
        anyhow::bail!(
            "Codex sandbox requires seccomp=unconfined in the generated docker-compose.yml, \
             but explicit consent has not been given.\n\
             \n\
             To opt in, add the following to your aibox.toml:\n\
             \n\
             [security]\n\
             acknowledge_seccomp_unconfined = true\n\
             \n\
             This setting documents that you accept the reduced seccomp filtering \
             required for bubblewrap user-namespace sandboxing."
        );
    }

    // Container home path
    let container_home = config.container_home();

    // GIT_CONFIG_GLOBAL must use the container home path
    env_vars.insert(
        "GIT_CONFIG_GLOBAL".to_string(),
        format!("{}/.config/git/config", container_home),
    );

    // Merge user-defined environment variables from aibox.toml (shared, safe to
    // commit). Variables from .aibox-local.toml (credentials) are handled
    // separately below — they go to .aibox-local.env, not into docker-compose.yml.
    for (k, v) in &config.container.environment {
        if !config.local_env.contains_key(k) {
            env_vars.insert(k.clone(), v.clone());
        }
    }

    // Escape values for YAML double-quoted strings
    let escaped_env: BTreeMap<String, String> = env_vars
        .iter()
        .map(|(k, v)| {
            let escaped = v.replace('\\', "\\\\").replace('"', "\\\"");
            (k.clone(), escaped)
        })
        .collect();

    let env_keys: Vec<String> = escaped_env.keys().cloned().collect();

    // Write .aibox-local.env even when empty so docker-compose env_file
    // references are stable while secrets remain outside committed files.
    let local_env_sorted: BTreeMap<&String, &String> = config.local_env.iter().collect();
    let env_content: String = local_env_sorted
        .iter()
        .map(|(k, v)| format!("{}={}\n", k, v))
        .collect();
    let local_env_path = project_path(&config.container.paths.local_env);
    if let Some(parent) = local_env_path.parent()
        && !parent.as_os_str().is_empty()
    {
        fs::create_dir_all(parent)
            .with_context(|| format!("Failed to create {}", parent.display()))?;
    }
    fs::write(&local_env_path, &env_content)
        .with_context(|| format!("Failed to write {}", local_env_path.display()))?;

    // Extra volumes from aibox.toml + .aibox-local.toml
    let extra_volumes = &config.container.extra_volumes;
    let runtime_home_mounts =
        crate::runtime_home::compose_runtime_home_mounts(config, &host_root_str);

    // Rust addon flag — drives cargo registry mounts in the template
    let compose_project_name = sanitize_compose_project_name(&config.container.name);
    let compose_image_name = format!("{}-devcontainer:latest", compose_project_name);
    let latex_preview_enabled = config.latex.preview.enabled && !config.latex.documents.is_empty();
    let latex_preview_documents = config
        .latex
        .documents
        .iter()
        .map(|document| {
            let stem = Path::new(&document.source)
                .file_stem()
                .unwrap_or_default()
                .to_string_lossy();
            serde_json::json!({
                "name": document.name,
                "source": document.source,
                "pdf": format!(
                    "/workspace/{}/{}.pdf",
                    document.output_dir.trim_end_matches('/'),
                    stem
                ),
            })
        })
        .collect::<Vec<_>>();
    let latex_preview_documents_json = serde_json::to_string(&latex_preview_documents)?
        .replace('\\', "\\\\")
        .replace('"', "\\\"");
    let latex_preview_preferred_document = config
        .latex
        .preview
        .document
        .as_deref()
        .or_else(|| {
            config
                .latex
                .documents
                .first()
                .map(|document| document.name.as_str())
        })
        .unwrap_or_default()
        .replace('\\', "\\\\")
        .replace('"', "\\\"");
    let latex_preview_bind: std::net::IpAddr = config
        .latex
        .preview
        .bind
        .parse()
        .expect("validated LaTeX preview bind address");
    let latex_preview_publish = match latex_preview_bind {
        std::net::IpAddr::V6(_) => format!(
            "[{}]:{}:8765",
            latex_preview_bind, config.latex.preview.port
        ),
        _ => format!("{}:{}:8765", latex_preview_bind, config.latex.preview.port),
    };

    let tmpl = env
        .get_template("docker-compose.yml")
        .context("Failed to load docker-compose template")?;
    let dockerfile_path = if legacy_dir_arg {
        path_or_dir.join("Dockerfile")
    } else {
        project_path(&config.container.paths.dockerfile)
    };
    let local_env_file = if legacy_dir_arg {
        "../.aibox-local.env".to_string()
    } else {
        relative_path(compose_dir, &local_env_path)
    };

    let content = tmpl
        .render(context! {
            header => header,
            project_name => compose_project_name,
            image_name => compose_image_name,
            name => config.container.name,
            hostname => config.container.hostname,
            user => config.container.user,
            workspace_dir => workspace_dir,
            host_root => host_root_str,
            container_home => container_home,
            dockerfile_path => if legacy_dir_arg {
                "Dockerfile".to_string()
            } else {
                relative_path(compose_dir, &dockerfile_path)
            },
            local_env_file => local_env_file,
            runtime_home_mounts => runtime_home_mounts,
            codex_sandbox_seccomp => codex_sandbox_seccomp,
            env_keys => env_keys,
            env_vals => escaped_env,
            extra_volumes => extra_volumes,
            latex_preview_enabled => latex_preview_enabled,
            latex_preview_documents_json => latex_preview_documents_json,
            latex_preview_preferred_document => latex_preview_preferred_document,
            latex_preview_publish => latex_preview_publish,
        })
        .context("Failed to render docker-compose template")?;

    write_if_changed(&compose_path, &content)
}

/// Generate devcontainer.json. Returns true if file was written.
fn generate_devcontainer_json(config: &AiboxConfig, path_or_dir: &Path) -> Result<bool> {
    let legacy_dir_arg = path_or_dir.is_dir();
    let devcontainer_json_path = if path_or_dir.is_dir() {
        path_or_dir.join("devcontainer.json")
    } else {
        path_or_dir.to_path_buf()
    };
    let name = &config.container.name;
    let addons = &config.addons;

    // Build extensions list
    let mut extensions: Vec<String> = vec![];
    if addons.has_python() {
        extensions.push("ms-python.python".to_string());
    }
    if addons.has_rust() {
        extensions.push("rust-lang.rust-analyzer".to_string());
    }
    if addons.has_latex() {
        extensions.push("james-yu.latex-workshop".to_string());
        extensions.push("mblode.zotero".to_string());
    }
    if addons.has_addon("typst") {
        extensions.push("myriad-dreamin.tinymist".to_string());
    }
    if addons.has_node() {
        extensions.push("dbaeumer.vscode-eslint".to_string());
    }
    if addons.has_addon("go") {
        extensions.push("golang.go".to_string());
    }

    // Build VS Code terminal profiles — include configured AI providers.
    // The tmux profile uses the layout from aibox.toml so VS Code terminals
    // match `aibox up`'s default.
    let layout = config.customization.tmux_layout().to_string();
    let mut terminal_profiles = serde_json::json!({
        "bash": {
            "path": "/bin/bash"
        },
        "tmux": {
            "path": "/bin/bash",
            "args": ["-lc", format!("exec ~/.config/tmux/layouts/{layout}.sh")]
        }
    });

    for provider in &config.ai.harnesses {
        // Cursor is a host-side IDE extension with no container binary.
        // All other providers have a container CLI installed by their addon.
        // Continue's binary is `cn` (not `continue`); use binary_name() for the path.
        if !provider.is_active() || matches!(provider, crate::config::AiProvider::Cursor) {
            continue;
        }
        let name = provider.binary_name();
        let path = format!("/usr/local/bin/{}", name);
        terminal_profiles
            .as_object_mut()
            .unwrap()
            .insert(name.to_string(), serde_json::json!({ "path": path }));
    }

    // Build VS Code settings — start with base, add flavor-specific
    let mut settings = serde_json::json!({
        "terminal.integrated.defaultProfile.linux": "bash",
        "terminal.integrated.fontFamily": "'FiraCode Nerd Font', 'Hack Nerd Font', 'JetBrainsMono Nerd Font', monospace",
        "terminal.integrated.profiles.linux": terminal_profiles
    });

    // LaTeX Workshop settings — matches proven setup from derived projects
    if addons.has_latex() {
        let latex_settings = serde_json::json!({
            "latex-workshop.latex.outDir": "./out",
            "latex-workshop.view.pdf.viewer": "tab",
            "latex-workshop.latex.tools": [
                {
                    "name": "latexmk-lualatex",
                    "command": "latexmk",
                    "args": [
                        "--shell-escape",
                        "-synctex=1",
                        "-interaction=nonstopmode",
                        "-file-line-error",
                        "-pdflatex=lualatex",
                        "-pdf",
                        "-aux-directory=./out",
                        "-output-directory=./out",
                        "%DOC%"
                    ]
                },
                {
                    "name": "latexmk-pdflatex",
                    "command": "latexmk",
                    "args": [
                        "-synctex=1",
                        "-interaction=nonstopmode",
                        "-file-line-error",
                        "-pdf",
                        "-aux-directory=./out",
                        "-output-directory=./out",
                        "%DOC%"
                    ]
                },
                {
                    "name": "biber",
                    "command": "biber",
                    "args": [
                        "--input-directory=out",
                        "--output-directory=out",
                        "%DOCFILE%"
                    ]
                }
            ],
            "latex-workshop.latex.recipes": [
                {
                    "name": "latexmk (lualatex)",
                    "tools": ["latexmk-lualatex"]
                },
                {
                    "name": "latexmk (pdflatex)",
                    "tools": ["latexmk-pdflatex"]
                },
                {
                    "name": "latexmk (lualatex) + biber",
                    "tools": ["latexmk-lualatex", "biber", "latexmk-lualatex"]
                }
            ],
            "latex-workshop.latex.autoBuild.run": "onSave",
            "latex-workshop.latex.clean.fileTypes": [
                "*.aux", "*.bbl", "*.blg", "*.fdb_latexmk", "*.fls",
                "*.log", "*.out", "*.synctex.gz", "*.toc", "*.lof",
                "*.lot", "*.nav", "*.snm", "*.vrb", "*.bcf", "*.run.xml"
            ]
        });
        for (k, v) in latex_settings.as_object().unwrap() {
            settings
                .as_object_mut()
                .unwrap()
                .insert(k.clone(), v.clone());
        }
    }

    // Detect docker-compose.override.yml — if present, VS Code needs both
    // files listed explicitly. Docker Compose CLI auto-merges overrides, but
    // devcontainer.json requires the array form to pick them up.
    let devcontainer_dir = parent_dir(&devcontainer_json_path);
    let compose_path = if path_or_dir.is_dir() {
        path_or_dir.join("docker-compose.yml")
    } else {
        project_path(&config.container.paths.docker_compose)
    };
    let compose_override_path = if path_or_dir.is_dir() {
        path_or_dir.join("docker-compose.override.yml")
    } else {
        project_path(&config.container.paths.docker_compose_override)
    };
    let compose_file: serde_json::Value = if legacy_dir_arg && compose_override_path.exists() {
        serde_json::json!(["docker-compose.yml", "docker-compose.override.yml"])
    } else if legacy_dir_arg {
        serde_json::json!("docker-compose.yml")
    } else if compose_override_path.exists() {
        serde_json::json!([
            relative_path(devcontainer_dir, &compose_path),
            relative_path(devcontainer_dir, &compose_override_path)
        ])
    } else {
        serde_json::json!(relative_path(devcontainer_dir, &compose_path))
    };

    // Use serde_json for proper JSON formatting
    let mut devcontainer = serde_json::json!({
        "name": name,
        "dockerComposeFile": compose_file,
        "service": name,
        "workspaceFolder": "/workspace",
        "overrideCommand": false,
        "remoteUser": config.container.user,
        "customizations": {
            "vscode": {
                "extensions": extensions,
                "settings": settings
            }
        }
    });

    // Insert postCreateCommand if configured
    let post_create_command = config
        .container
        .lifecycle
        .post_create_command
        .as_ref()
        .or(config.container.post_create_command.as_ref());
    if let Some(cmd) = post_create_command {
        devcontainer
            .as_object_mut()
            .unwrap()
            .insert("postCreateCommand".to_string(), serde_json::json!(cmd));
    }

    let mut post_start_commands: Vec<String> = Vec::new();

    // Network keepalive — lightweight DNS lookup every 2 min to prevent
    // OrbStack/VM NAT from dropping idle connections.
    if config.container.lifecycle.keepalive || config.container.keepalive {
        post_start_commands.push(
            "nohup bash -c 'while true; do nslookup example.com > /dev/null 2>&1; sleep 120; done' > /dev/null 2>&1 &"
                .to_string(),
        );
    }
    if should_start_processkit_gateway_daemon(config, devcontainer_dir) {
        let gateway = &config.mcp.gateway;
        let mut env = "UV_CACHE_DIR=/tmp/aibox/uv-cache PROCESSKIT_MCP_MODE=gateway".to_string();
        if gateway.lazy_catalog {
            env.push_str(
                " PROCESSKIT_GATEWAY_IMPORT_MODE=lazy-catalog PROCESSKIT_GATEWAY_LAZY=true",
            );
        }
        let catalog_command = if gateway.lazy_catalog {
            format!(
                "{env} uv run context/skills/processkit/processkit-gateway/mcp/server.py catalog --write >/tmp/aibox/processkit-gateway-catalog.log 2>&1 || true; "
            )
        } else {
            String::new()
        };
        let serve_command = format!(
            "{env} nohup uv run context/skills/processkit/processkit-gateway/mcp/server.py serve --transport streamable-http --host {} --port {} >/tmp/aibox/processkit-gateway.log 2>&1 &",
            gateway.host, gateway.port
        );
        post_start_commands.push(format!(
            "if ! pgrep -f 'processkit-gateway/mcp/server.py.*streamable-http' >/dev/null 2>&1; then mkdir -p /tmp/aibox/uv-cache; (cd /workspace && {catalog_command}{serve_command}); fi"
        ));
    }
    if !post_start_commands.is_empty() {
        devcontainer.as_object_mut().unwrap().insert(
            "postStartCommand".to_string(),
            serde_json::json!(post_start_commands.join("; ")),
        );
    }

    // Prevent VS Code from auto-forwarding the PulseAudio port (fixes #11)
    let audio = if config.container.audio.enabled {
        &config.container.audio
    } else {
        &config.audio
    };
    if audio.enabled {
        // Extract port from pulse_server string (e.g., "tcp:host.docker.internal:4714")
        let port = audio.pulse_server.rsplit(':').next().unwrap_or("4714");
        devcontainer.as_object_mut().unwrap().insert(
            "portsAttributes".to_string(),
            serde_json::json!({
                port: { "onAutoForward": "ignore" }
            }),
        );
    }

    // Serialize with pretty formatting
    let json_str = serde_json::to_string_pretty(&devcontainer)
        .context("Failed to serialize devcontainer.json")?;

    // Add the header as a comment at the top (JSON doesn't support comments,
    // but devcontainer.json does via jsonc). v0.18.7: version-free header to
    // avoid rebuild churn (see HEADER_TEMPLATE comment).
    let header = "// Generated by aibox — do not edit manually.\n// To modify, edit aibox.toml and run: aibox apply\n".to_string();
    let _ = config; // version no longer interpolated; placeholder reference.

    write_if_changed(
        &devcontainer_json_path,
        &format!("{}{}\n", header, json_str),
    )
}

/// Public wrapper around `compose_override_declares_codex_seccomp` for callers
/// outside this module (e.g., the apply consent gate in container.rs).
pub fn compose_override_declares_codex_seccomp_pub(
    override_path: &Path,
    service_name: &str,
) -> bool {
    compose_override_declares_codex_seccomp(override_path, service_name)
}

fn compose_override_declares_codex_seccomp(override_path: &Path, service_name: &str) -> bool {
    let Ok(content) = fs::read_to_string(override_path) else {
        return false;
    };
    let Ok(compose) = serde_yaml::from_str::<serde_yaml::Value>(&content) else {
        return false;
    };
    compose_services(&compose).is_some_and(|services| {
        services
            .get(serde_yaml::Value::String(service_name.to_string()))
            .is_some_and(|service| {
                service
                    .get("security_opt")
                    .is_some_and(|value| yaml_value_contains_ci(value, "seccomp=unconfined"))
            })
    })
}

fn compose_services(compose: &serde_yaml::Value) -> Option<&serde_yaml::Mapping> {
    compose.get("services")?.as_mapping()
}

fn yaml_value_contains_ci(value: &serde_yaml::Value, needle: &str) -> bool {
    if let Some(text) = value.as_str() {
        return text.eq_ignore_ascii_case(needle);
    }
    value
        .as_sequence()
        .map(|items| {
            items.iter().any(|item| {
                item.as_str()
                    .map(|text| text.eq_ignore_ascii_case(needle))
                    .unwrap_or(false)
            })
        })
        .unwrap_or(false)
}

fn should_start_processkit_gateway_daemon(config: &AiboxConfig, _devcontainer_dir: &Path) -> bool {
    if !config.processkit_enabled() {
        return false;
    }
    match config.mcp.gateway.mode {
        McpGatewayMode::DaemonProxy => true,
        // processkit v0.25.4 made stdio-proxy own local daemon startup by
        // default. In auto mode, prefer that self-starting proxy over a
        // devcontainer postStartCommand that can race MCP client startup.
        McpGatewayMode::Auto
        | McpGatewayMode::Granular
        | McpGatewayMode::Stdio
        | McpGatewayMode::Aggregate
        | McpGatewayMode::LazyAggregate => false,
    }
}

